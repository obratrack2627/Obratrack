import { test, expect } from '@playwright/test';
import { setup } from './helpers/platform';

test('crear una obra registra el nuevo cliente y permite reutilizarlo sin duplicar fichas', async ({ page }) => {
  const db = await setup(page, {});
  await page.goto('/proyectos');
  await page.getByRole('button', { name: 'Nueva obra', exact: true }).click();
  await page.locator('#create-project-name').fill('Ampliación cocina');
  await page.getByLabel('Cliente de la nueva obra').selectOption('__nuevo__');
  await page.getByLabel('Nombre del cliente *', { exact: true }).fill('María Mandante');
  await page.getByLabel('Teléfono del cliente *', { exact: true }).fill('912345678');
  await page.getByLabel('Correo del cliente *', { exact: true }).fill('maria@example.test');
  await page.getByRole('button', { name: 'Crear Proyecto', exact: true }).click();
  await expect.poll(() => db.clientes?.length).toBe(1);
  await expect.poll(() => db.proyectos.length).toBe(1);
  expect(db.clientes[0]).toMatchObject({ nombre: 'María Mandante', telefono: '+56912345678', email: 'maria@example.test' });
  expect(db.proyectos[0].cliente_id).toBe(db.clientes[0].id);
  await page.getByRole('button', { name: 'Nueva obra', exact: true }).click();
  await page.locator('#create-project-name').fill('Segunda obra');
  await page.getByLabel('Cliente de la nueva obra').selectOption(db.clientes[0].id);
  await page.getByRole('button', { name: 'Crear Proyecto', exact: true }).click();
  await expect.poll(() => db.proyectos.length).toBe(2);
  expect(db.clientes).toHaveLength(1);
  expect(db.proyectos.find(p => p.nombre === 'Segunda obra')?.cliente_id).toBe(db.clientes[0].id);
});

test('clientes permite asociar obras al crear y editar, y conserva las otras obras', async ({ page }) => {
  const db = await setup(page, {}, true);
  db.proyectos.push({ ...db.proyectos[0], id: 'p-second', nombre: 'Quincho' });
  await page.goto('/clientes');
  await expect.poll(async () => page.evaluate(() => JSON.parse(localStorage.getItem('obratrack_proyectos_v7_fixture-company') || '[]').length)).toBe(2);
  await page.getByRole('button', { name: 'Nuevo Cliente', exact: true }).click();
  const create = page.locator('form').filter({ has: page.getByRole('button', { name: 'Crear Cliente', exact: true }) });
  await create.locator('input[type=text]').first().fill('Pedro Mandante');
  await create.getByRole('checkbox', { name: /Terraza/ }).check();
  await create.getByRole('button', { name: 'Crear Cliente', exact: true }).click();
  await expect.poll(() => db.clientes?.length).toBe(1);
  await expect.poll(() => db.proyectos[0].cliente_id).toBe(db.clientes[0].id);
  expect(db.proyectos[1].cliente_id).toBeUndefined();
  await page.getByRole('button', { name: /Editar/ }).first().click();
  const edit = page.locator('form').filter({ has: page.getByRole('button', { name: 'Guardar Cambios', exact: true }) });
  await expect(edit.getByRole('checkbox', { name: /Terraza/ })).toBeChecked();
  await edit.getByRole('checkbox', { name: /Quincho/ }).check();
  await edit.getByRole('button', { name: 'Guardar Cambios', exact: true }).click();
  await expect.poll(() => db.proyectos[1].cliente_id).toBe(db.clientes[0].id);
  expect(db.proyectos[0].cliente_id).toBe(db.clientes[0].id);
  await page.getByRole('button', { name: /Editar/ }).first().click();
  await edit.getByRole('checkbox', { name: /Terraza/ }).uncheck();
  await edit.getByRole('button', { name: 'Guardar Cambios', exact: true }).click();
  await expect.poll(() => db.proyectos[0].cliente_id || '').toBe('');
  expect(db.proyectos[1].cliente_id).toBe(db.clientes[0].id);
  await page.getByRole('button', { name: 'Nuevo Cliente', exact: true }).click();
  await create.locator('input[type=text]').first().fill('Ana Mandante');
  await create.getByRole('checkbox', { name: /Quincho/ }).check();
  await expect(create.getByText(/la selección lo reemplazará/)).toBeVisible();
  await create.getByRole('button', { name: 'Crear Cliente', exact: true }).click();
  await expect.poll(() => db.clientes.length).toBe(2);
  await expect.poll(() => db.proyectos[1].cliente_id).toBe(db.clientes.find(c => c.nombre === 'Ana Mandante')!.id);
});
